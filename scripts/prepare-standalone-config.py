#!/usr/bin/env python3
"""Seed the per-user standalone configuration for OneStats on THIS PC.

Writes `%LOCALAPPDATA%\\OneStats\\onestats.env` with the local database connection (and encryption
key / optional connector keys) copied from the development `.env`, so the packaged standalone backend
reaches the SAME local PostgreSQL and the SAME `onestats` database — preserving all existing data.

It is non-destructive: it never touches the database, and by default it will NOT overwrite an existing
per-user config unless `--force` is given. Secrets are written only to the user-private AppData file,
never to source control. Run once when preparing the standalone install (docs/75-standalone-windows.md).
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

# Keys carried from dev .env into the per-user standalone config (DB + encryption + optional connectors).
CARRY = [
    "ONESTATS_DB_HOST", "ONESTATS_DB_PORT", "ONESTATS_DB_NAME", "ONESTATS_DB_USER",
    "ONESTATS_DB_PASSWORD", "ONESTATS_MIGRATOR_PASSWORD", "ONESTATS_DB_URL",
    "ONESTATS_ENCRYPTION_KEY",
    "ONESTATS_PLAYHQ_API_KEY", "ONESTATS_PLAYHQ_TENANT", "ONESTATS_PLAYHQ_ORG_ID",
]


def _parse_env_file(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.exists():
        return out
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, _, v = line.partition("=")
        out[k.strip()] = v.strip().strip('"').strip("'")
    return out


def _data_dir() -> Path:
    override = os.environ.get("ONESTATS_DATA_DIR")
    if override:
        return Path(override)
    root = os.environ.get("LOCALAPPDATA") or os.environ.get("APPDATA")
    return (Path(root) / "OneStats") if root else (Path.home() / ".onestats")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="Seed the standalone per-user config from the dev .env.")
    ap.add_argument("--dev-env", default=str(Path(__file__).resolve().parents[1] / "services" / "api" / ".env"))
    ap.add_argument("--force", action="store_true", help="Overwrite an existing per-user config.")
    args = ap.parse_args(argv)

    dev_env = Path(args.dev_env)
    source = _parse_env_file(dev_env)
    # Environment takes precedence over the file (so this also works when values are only in the env).
    values = {k: os.environ.get(k, source.get(k)) for k in CARRY}
    values = {k: v for k, v in values.items() if v}

    if not (values.get("ONESTATS_DB_PASSWORD") or values.get("ONESTATS_DB_URL")):
        print("ERROR: no database credential found in the dev .env/environment; nothing to seed.", file=sys.stderr)
        return 2

    target_dir = _data_dir()
    target = target_dir / "onestats.env"
    if target.exists() and not args.force:
        print(f"Per-user config already exists: {target}\nUse --force to overwrite.", file=sys.stderr)
        return 1

    target_dir.mkdir(parents=True, exist_ok=True)
    lines = [
        "# OneStats standalone (per-user) configuration — generated by prepare-standalone-config.py.",
        "# Secrets live only here (user-private AppData), never in source control.",
        "ONESTATS_ENV=production",
    ]
    lines += [f"{k}={v}" for k, v in values.items()]
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        os.chmod(target, 0o600)  # best-effort tighten (no-op semantics on some Windows setups)
    except OSError:
        pass

    shown = ", ".join(k for k in values if "PASSWORD" not in k and "KEY" not in k and "URL" not in k)
    print(f"Wrote {target}")
    print(f"  carried: {shown} (+ secrets, not shown)")
    print("  The standalone backend will use your existing local PostgreSQL and 'onestats' database.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
